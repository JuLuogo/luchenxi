/*!
 * scripts/gen-protocol.mjs — 从契约生成 Rust 常量，杜绝"两端报文名漂移"
 *
 *  契约来源：packages/protocol/messages.js
 *  生成目标：apps/teacher/src-tauri/src/protocol_gen.rs
 *
 *  为什么要有代码生成：报文名/字段名在 JS 侧是字符串，在 Rust 侧也是字符串，
 *  编译器管不到。让 Rust 侧只使用生成出来的常量，再让测试校验"生成文件是最新的"，
 *  就能在 CI 里拦住任何单边改动。
 *
 *  用法：
 *    node scripts/gen-protocol.mjs           # 写入
 *    node scripts/gen-protocol.mjs --check   # 只校验是否最新（CI 用，不一致则非 0 退出）
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const P = require(path.join(ROOT, 'packages', 'protocol', 'messages.js'));

const TARGET = path.join(ROOT, 'apps', 'teacher', 'src-tauri', 'src', 'protocol_gen.rs');

function rustStrArray(name, items, doc) {
  const rows = items.map((s) => '    "' + s + '",').join('\n');
  return `/// ${doc}\npub const ${name}: &[&str] = &[\n${rows}\n];\n`;
}

function build() {
  const types = P.typeList().sort();
  const clientTypes = Object.keys(P.CLIENT_TO_HUB).sort();
  const hubTypes = Object.keys(P.HUB_TO_CLIENT).sort();
  const snapshot = Object.keys(P.SNAPSHOT_FIELDS).sort();
  const metaFields = Object.keys(P.SNAPSHOT_FIELDS.meta).sort();
  const cmdKinds = Object.keys(P.CMD_KINDS).sort();

  return [
    '//! @generated by scripts/gen-protocol.mjs —— 请勿手改；改契约请编辑 packages/protocol/messages.js',
    '//!',
    '//! 这样 Rust 枢纽与 Node 枢纽引用的报文名来自同一份契约，',
    '//! 并由 tests/protocol.test.js 校验本文件始终是最新的。',
    '',
    `/// 协议版本（与 packages/protocol/messages.js 的 version 一致）`,
    `pub const PROTOCOL_VERSION: u32 = ${P.version};`,
    '',
    rustStrArray('ALL_TYPES', types, '全部报文类型'),
    rustStrArray('CLIENT_TO_HUB', clientTypes, '客户端 → 枢纽'),
    rustStrArray('HUB_TO_CLIENT', hubTypes, '枢纽 → 客户端'),
    rustStrArray('CMD_KINDS', cmdKinds, 'cmd.kind 取值'),
    rustStrArray('SNAPSHOT_FIELDS', snapshot, '快照顶层字段'),
    rustStrArray('META_FIELDS', metaFields, 'meta 字段'),
    ''
  ].join('\n');
}

const content = build();
const checkOnly = process.argv.includes('--check');
const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';

if (checkOnly) {
  if (current === content) {
    console.log('[ok] protocol_gen.rs 与契约一致（' + content.split('\n').length + ' 行）');
    process.exit(0);
  }
  console.error('[stale] protocol_gen.rs 与 packages/protocol/messages.js 不一致');
  console.error('        运行 node scripts/gen-protocol.mjs 重新生成');
  process.exit(1);
}

if (current === content) {
  console.log('[same] protocol_gen.rs 已是最新，无需写入');
} else {
  fs.mkdirSync(path.dirname(TARGET), { recursive: true });
  fs.writeFileSync(TARGET, content, 'utf8');
  console.log('[write] ' + path.relative(ROOT, TARGET) + '（' + content.split('\n').length + ' 行）');
}
