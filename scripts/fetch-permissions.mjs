/*!
 * scripts/fetch-permissions.mjs — 从 Tauri 插件 crate 里提取**真实存在**的权限标识，入库供离线校验
 *
 *  为什么：capabilities 里写 `shell:allow-open` 这种标识，写错了本地没感觉，构建时才报错。
 *  真名来自各插件 crate 的 `permissions/**.toml`，所以这里直接下载 crate（crates.io 的 .crate 即 tar.gz），
 *  解出 permissions 目录下的 `identifier = "..."`，生成清单提交进仓库。
 *
 *  用法：
 *    node scripts/fetch-permissions.mjs            # 下载并刷新 packages/schema/plugin-permissions.json
 *    node scripts/fetch-permissions.mjs --check    # 只检查清单是否存在（离线校验用）
 */
import fs from 'node:fs';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'packages', 'schema', 'plugin-permissions.json');
const UA = 'luchenxi-permissions-check (https://github.com/JuLuogo/luchenxi)';

/** 需要核对权限的 crate（名字 → 在 capabilities 里的前缀） */
const CRATES = {
  tauri: 'core',
  'tauri-plugin-shell': 'shell',
  'tauri-plugin-dialog': 'dialog'
};

if (process.argv.includes('--check')) {
  if (fs.existsSync(OUT)) {
    const m = JSON.parse(fs.readFileSync(OUT, 'utf8'));
    console.log('[ok] 权限清单已入库（' + Object.keys(m.crates).length + ' 个 crate，' +
      Object.values(m.crates).reduce((n, c) => n + c.identifiers.length, 0) + ' 个标识）');
    process.exit(0);
  }
  console.error('[missing] 未找到 ' + path.relative(ROOT, OUT) + '；运行 node scripts/fetch-permissions.mjs');
  process.exit(1);
}

/** 解析 tar（ustar）并返回 [{ name, content }] */
function readTar(buf) {
  const out = [];
  let off = 0;
  while (off + 512 <= buf.length) {
    const header = buf.subarray(off, off + 512);
    const name = header.subarray(0, 100).toString('utf8').replace(/\0.*$/, '');
    if (!name) break;
    const sizeStr = header.subarray(124, 136).toString('utf8').replace(/\0.*$/, '').trim();
    const size = parseInt(sizeStr, 8) || 0;
    const content = buf.subarray(off + 512, off + 512 + size);
    out.push({ name: name, content: content });
    off += 512 + Math.ceil(size / 512) * 512;
  }
  return out;
}

/**
 * 从 crate 里提取权限标识。两种来源：
 *   ① 插件：permissions/**.toml
 *      · `identifier = "allow-open"` → shell:allow-open
 *      · 顶层 permissions/<set>.toml 的文件名即权限集名 → shell:default
 *   ② 核心（tauri crate）：permissions/<module>/autogenerated/reference.md 里的 `core:xxx:yyy`
 */
function extractIdentifiers(crate, prefix, entries) {
  const ids = new Set();
  entries.filter((e) => /(^|\/)permissions\/.*\.toml$/.test(e.name)).forEach((e) => {
    const text = e.content.toString('utf8');
    const re = /^\s*identifier\s*=\s*"([^"]+)"/gm;
    let m;
    while ((m = re.exec(text))) ids.add(prefix + ':' + m[1]);
    // 顶层 permissions/xxx.toml 的 xxx 就是权限集名（如 default）
    const top = e.name.match(/(?:^|\/)permissions\/([A-Za-z0-9_-]+)\.toml$/);
    if (top) ids.add(prefix + ':' + top[1]);
  });
  if (crate === 'tauri') {
    entries.filter((e) => /permissions\/.*\.md$/.test(e.name)).forEach((e) => {
      const text = e.content.toString('utf8');
      const re = /`(core:[a-z0-9-]+(?::[a-z0-9-]+)?)`/g;
      let m;
      while ((m = re.exec(text))) ids.add(m[1]);
    });
    // 核心的 `core:default` 权限集不在 crate 文件里，而是由 tauri 的 build.rs 在构建时生成
    // （ACL 生成器写入 OUT_DIR/permissions/default.toml）。build.rs 里的错误信息是权威证据。
    const buildRs = entries.find((e) => /(^|\/)build\.rs$/.test(e.name));
    if (buildRs && buildRs.content.toString('utf8').indexOf('core:default') >= 0) {
      ids.add('core:default');
    }
  }
  return ids;
}

async function latestMatching(name, req) {
  const res = await fetch('https://crates.io/api/v1/crates/' + name, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error('查询 ' + name + ' 失败：HTTP ' + res.status);
  const data = await res.json();
  const versions = (data.versions || []).filter((v) => !v.yanked).map((v) => v.num);
  const major = req.split('.')[0];
  const picked = versions.find((v) => v.split('.')[0] === major && !/-/.test(v));
  if (!picked) throw new Error(name + ' 找不到匹配 ' + req + ' 的版本');
  return picked;
}

const manifest = {
  generatedAt: new Date().toISOString(),
  note: '由 scripts/fetch-permissions.mjs 从各 crate 的 permissions/**.toml、**.md 与 build.rs 提取；capabilities 里用的标识必须在此清单内。core:default 由 tauri 的 build.rs 在构建时生成（不在 crate 文件里），依据其错误信息中的字面量收录。',
  crates: {}
};

let failed = null;
for (const [crate, prefix] of Object.entries(CRATES)) {
  try {
    const req = crate === 'tauri' ? '2' : '2';
    const ver = await latestMatching(crate, req);
    const url = 'https://crates.io/api/v1/crates/' + crate + '/' + ver + '/download';
    const res = await fetch(url, { headers: { 'User-Agent': UA }, redirect: 'follow' });
    if (!res.ok) throw new Error('下载失败 HTTP ' + res.status);
    const gz = Buffer.from(await res.arrayBuffer());
    const tar = zlib.gunzipSync(gz);
    const entries = readTar(tar);
    const ids = extractIdentifiers(crate, prefix, entries);
    manifest.crates[crate] = { version: ver, prefix: prefix, identifiers: [...ids].sort() };
    console.log('[ok] ' + crate + '@' + ver + ' → ' + ids.size + ' 个标识');
  } catch (e) {
    failed = crate + '：' + (e.cause && e.cause.message ? e.cause.message : e.message);
    console.error('[fail] ' + failed);
  }
}

if (failed) {
  console.error('\n未能完成抓取：' + failed);
  process.exit(1);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, JSON.stringify(manifest, null, 2), 'utf8');
console.log('[write] ' + path.relative(ROOT, OUT));
Object.entries(manifest.crates).forEach(([c, v]) => {
  console.log('  ' + c + '@' + v.version + '：' + v.identifiers.slice(0, 8).join(', ') + (v.identifiers.length > 8 ? ' …' : ''));
});
